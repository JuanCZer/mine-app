import { randomUUID } from 'node:crypto';
import { mkdir, open, readFile, rename, unlink } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseEnv } from 'node:util';

const modulePath = fileURLToPath(import.meta.url);
const defaultProjectRoot = path.resolve(path.dirname(modulePath), '..');
const publicVariableName = 'MAPBOX_PUBLIC_TOKEN';
const publicTokenPattern = /^pk\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/;

async function readEnvironmentFile(filePath) {
  try {
    return parseEnv(await readFile(filePath, 'utf8'));
  } catch (error) {
    if (error?.code === 'ENOENT') {
      return {};
    }
    throw error;
  }
}

async function writeFileAtomically(destination, source) {
  const temporaryPath = path.join(
    path.dirname(destination),
    `.${path.basename(destination)}.${randomUUID()}.tmp`,
  );
  let fileHandle;
  let temporaryCreated = false;

  try {
    fileHandle = await open(temporaryPath, 'wx', 0o666);
    temporaryCreated = true;
    await fileHandle.writeFile(source, 'utf8');
    await fileHandle.sync();
    await fileHandle.close();
    fileHandle = undefined;
    await rename(temporaryPath, destination);
  } catch (operationError) {
    const cleanupErrors = [];
    if (fileHandle !== undefined) {
      try {
        await fileHandle.close();
      } catch (error) {
        cleanupErrors.push(error);
      }
    }
    if (temporaryCreated) {
      try {
        await unlink(temporaryPath);
      } catch (error) {
        if (error?.code !== 'ENOENT') {
          cleanupErrors.push(error);
        }
      }
    }
    if (cleanupErrors.length > 0) {
      throw new AggregateError(
        [operationError, ...cleanupErrors],
        'Public environment generation and temporary-file cleanup failed.',
      );
    }
    throw operationError;
  }
}

export async function generatePublicConfig({
  projectRoot = defaultProjectRoot,
  env = process.env,
} = {}) {
  const fileEnvironment = await readEnvironmentFile(path.join(projectRoot, '.env'));
  const token = Object.hasOwn(env, publicVariableName)
    ? env[publicVariableName]
    : fileEnvironment[publicVariableName];

  if (typeof token !== 'string' || token.trim() === '') {
    throw new Error('MAPBOX_PUBLIC_TOKEN is required.');
  }
  if (!publicTokenPattern.test(token)) {
    throw new Error('MAPBOX_PUBLIC_TOKEN must be a valid public Mapbox token.');
  }

  const destination = path.join(projectRoot, 'src/app/core/config/public-env.generated.ts');
  const source = [
    '// Generated by scripts/generate-public-env.mjs. Do not edit.',
    'export const PUBLIC_ENV: Readonly<{ mapboxPublicToken: string }> =',
    '  Object.freeze({',
    `    mapboxPublicToken: ${JSON.stringify(token)},`,
    '  });',
    '',
  ].join('\n');

  await mkdir(path.dirname(destination), { recursive: true });
  await writeFileAtomically(destination, source);
}

const isCli =
  process.argv[1] !== undefined &&
  pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;

if (isCli) {
  try {
    await generatePublicConfig();
  } catch (error) {
    console.error(error instanceof Error ? error.message : 'Public environment generation failed.');
    process.exitCode = 1;
  }
}
