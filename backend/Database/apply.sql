CREATE OR REPLACE FUNCTION app.initialize_incident_phases()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_stage text;
    v_phase_id uuid;
BEGIN
    FOREACH v_stage IN ARRAY ARRAY['indications', 'reconnaissance', 'surveillance', 'mitigation'] LOOP
        INSERT INTO app.incident_phases(incident_id, stage_code)
        VALUES (NEW.id, v_stage)
        RETURNING id INTO v_phase_id;

        INSERT INTO app.phase_reviews(phase_id) VALUES (v_phase_id);
        CASE v_stage
            WHEN 'indications' THEN INSERT INTO app.phase_indications(phase_id) VALUES (v_phase_id);
            WHEN 'reconnaissance' THEN INSERT INTO app.phase_reconnaissance(phase_id) VALUES (v_phase_id);
            WHEN 'surveillance' THEN INSERT INTO app.phase_surveillance(phase_id) VALUES (v_phase_id);
            WHEN 'mitigation' THEN INSERT INTO app.phase_mitigation(phase_id) VALUES (v_phase_id);
        END CASE;
    END LOOP;
    RETURN NEW;
END $$;

