    ON app.legacy_batch_records(legacy_record_id, batch_id);

-- Upgrade databases produced by the previous direct-SQL contract. That
-- importer archived records sequentially, so creation order is the only
-- recoverable source-index ordering. Batches already using explicit links are
-- excluded, which keeps this backfill idempotent.
WITH ranked AS (
    SELECT
        r.batch_id,
        (row_number() OVER (PARTITION BY r.batch_id ORDER BY r.created_at, r.id) - 1)::integer AS source_index,
        r.id AS legacy_record_id,
        r.disposition,
        r.error_code,
        r.error_detail,
        r.processed_at
    FROM app.legacy_records r
    WHERE NOT EXISTS (
        SELECT 1 FROM app.legacy_batch_records existing
        WHERE existing.batch_id=r.batch_id
    )
)
INSERT INTO app.legacy_batch_records(
    batch_id, source_index, legacy_record_id, disposition, error_code, error_detail, processed_at)
SELECT
    batch_id,
    source_index,
    legacy_record_id,
    disposition,
    CASE
        WHEN disposition IN ('pending','imported') THEN NULL
        WHEN disposition='reconciliation_required' THEN
            COALESCE(NULLIF(btrim(error_code), ''), 'legacy-backfill-reconciliation-required')
        WHEN disposition='rejected' THEN
            COALESCE(NULLIF(btrim(error_code), ''), 'legacy-backfill-rejected')
    END AS error_code,
    CASE
        WHEN disposition IN ('pending','imported') THEN NULL
        ELSE error_detail
    END AS error_detail,
    processed_at
FROM ranked
ON CONFLICT (batch_id, source_index) DO NOTHING;

-- A previous importer could mark a batch complete without every declared
-- occurrence archived or while an occurrence remained pending. Reopen those
-- batches so a reviewed rerun must finish them before cutover.
WITH totals AS (
    SELECT
        b.id,
        count(br.source_index)::integer AS linked_count,
        count(*) FILTER (WHERE br.disposition='pending')::integer AS pending_count
    FROM app.import_batches b
    LEFT JOIN app.legacy_batch_records br ON br.batch_id=b.id
    LEFT JOIN app.legacy_records r ON r.id=br.legacy_record_id
    GROUP BY b.id
)
UPDATE app.import_batches b
SET status='running', completed_at=NULL
FROM totals
WHERE totals.id=b.id
  AND b.status IN ('completed','completed_with_errors')
  AND (totals.linked_count <> b.record_count OR totals.pending_count > 0);

