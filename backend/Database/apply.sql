CREATE OR REPLACE FUNCTION app.guard_phase_validation_insert()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_incident_id uuid;
    v_stage text;
    v_status text;
    v_prior_required integer;
    v_prior_validated integer;
BEGIN
    IF NEW.origin = 'legacy' AND NOT pg_has_role(current_user, 'gds_db_deployer', 'member') THEN
        RAISE EXCEPTION 'legacy validations require the database deployment role' USING ERRCODE = '42501';
    END IF;
    SELECT p.incident_id, p.stage_code, i.status_code
      INTO v_incident_id, v_stage, v_status
      FROM app.incident_phases p
      JOIN app.incidents i ON i.id = p.incident_id
     WHERE p.id = NEW.phase_id
     FOR UPDATE OF i;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'phase does not exist' USING ERRCODE = '23503';
    END IF;
    IF v_status <> 'open' THEN
        RAISE EXCEPTION 'incident is not open' USING ERRCODE = '55000';
    END IF;
    v_prior_required := CASE v_stage
        WHEN 'indications' THEN 0 WHEN 'reconnaissance' THEN 1
        WHEN 'surveillance' THEN 2 WHEN 'mitigation' THEN 3 ELSE 99 END;
    SELECT count(*) INTO v_prior_validated
      FROM app.phase_validations v
      JOIN app.incident_phases p ON p.id = v.phase_id
     WHERE p.incident_id = v_incident_id
       AND CASE p.stage_code WHEN 'indications' THEN 1 WHEN 'reconnaissance' THEN 2
                            WHEN 'surveillance' THEN 3 WHEN 'mitigation' THEN 4 END <= v_prior_required;
    IF v_prior_validated <> v_prior_required THEN
        RAISE EXCEPTION 'previous workflow phases must be validated first' USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION app.apply_validation_transition()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_incident_id uuid; v_stage text; v_finding text;
BEGIN
    SELECT p.incident_id, p.stage_code, r.finding_code
      INTO v_incident_id, v_stage, v_finding
      FROM app.incident_phases p JOIN app.phase_reviews r ON r.phase_id=p.id
     WHERE p.id=NEW.phase_id;
    IF v_stage = 'reconnaissance' AND v_finding = 'false-positive' THEN
        UPDATE app.incidents SET status_code='discarded' WHERE id=v_incident_id;
    ELSIF v_stage = 'mitigation' THEN
        UPDATE app.incidents SET status_code='closed' WHERE id=v_incident_id;
    END IF;
    RETURN NEW;
END $$;

