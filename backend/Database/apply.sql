CREATE OR REPLACE FUNCTION app.touch_catalog_option()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    NEW.version := OLD.version + 1;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_catalog_options_touch ON app.catalog_options;
CREATE TRIGGER trg_catalog_options_touch
BEFORE UPDATE ON app.catalog_options
FOR EACH ROW EXECUTE FUNCTION app.touch_catalog_option();

