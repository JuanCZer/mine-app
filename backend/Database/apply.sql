CREATE OR REPLACE FUNCTION app.assert_phase_mutable(p_phase_id uuid)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    v_status text;
    v_deleted_at timestamptz;
BEGIN
    SELECT i.status_code, i.deleted_at
      INTO v_status, v_deleted_at
      FROM app.incident_phases p
      JOIN app.incidents i ON i.id = p.incident_id
     WHERE p.id = p_phase_id
     FOR UPDATE OF i;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'phase % does not exist', p_phase_id USING ERRCODE = '23503';
    END IF;
    IF v_deleted_at IS NOT NULL OR v_status <> 'open' THEN
        RAISE EXCEPTION 'phase belongs to a closed, discarded, or deleted incident' USING ERRCODE = '55000';
    END IF;
    IF EXISTS (SELECT 1 FROM app.phase_validations WHERE phase_id = p_phase_id) THEN
        RAISE EXCEPTION 'validated phase is immutable' USING ERRCODE = '55000';
    END IF;
END $$;

CREATE OR REPLACE FUNCTION app.guard_phase_row_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM app.assert_phase_mutable(CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END);
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;

CREATE OR REPLACE FUNCTION app.guard_phase_child_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.phase_id IS DISTINCT FROM OLD.phase_id THEN
        -- Reparenting must not be used to remove a row from a validated phase.
        PERFORM app.assert_phase_mutable(OLD.phase_id);
        PERFORM app.assert_phase_mutable(NEW.phase_id);
    ELSE
        PERFORM app.assert_phase_mutable(CASE WHEN TG_OP = 'DELETE' THEN OLD.phase_id ELSE NEW.phase_id END);
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;

DROP TRIGGER IF EXISTS trg_guard_incident_phase ON app.incident_phases;
CREATE TRIGGER trg_guard_incident_phase BEFORE UPDATE OR DELETE ON app.incident_phases
FOR EACH ROW EXECUTE FUNCTION app.guard_phase_row_mutation();

DO $guards$
DECLARE v_table text;
BEGIN
    FOREACH v_table IN ARRAY ARRAY[
        'phase_reviews', 'phase_indications', 'phase_reconnaissance', 'phase_surveillance',
        'phase_mitigation', 'phase_indication_signatures', 'phase_radio_technologies',
        'phase_surveillance_methods', 'phase_evidence'
    ] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_guard_mutation ON app.%I', v_table);
        EXECUTE format(
            'CREATE TRIGGER trg_guard_mutation BEFORE INSERT OR UPDATE OR DELETE ON app.%I '
            'FOR EACH ROW EXECUTE FUNCTION app.guard_phase_child_mutation()', v_table
        );
    END LOOP;
END $guards$;

CREATE OR REPLACE FUNCTION app.guard_incident_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_has_validation boolean;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'physical deletion of incidents is forbidden; use soft deletion' USING ERRCODE = '55000';
    END IF;
    IF OLD.deleted_at IS NOT NULL THEN
        RAISE EXCEPTION 'deleted incident is immutable' USING ERRCODE = '55000';
    END IF;
    IF NEW.revision < OLD.revision OR NEW.revision > OLD.revision + 1 THEN
        RAISE EXCEPTION 'incident revision must advance by at most one' USING ERRCODE = '40001';
    END IF;
    SELECT EXISTS (
        SELECT 1 FROM app.phase_validations v
        JOIN app.incident_phases p ON p.id = v.phase_id
        WHERE p.incident_id = OLD.id
    ) INTO v_has_validation;
    IF v_has_validation AND (
        NEW.owner_user_id IS DISTINCT FROM OLD.owner_user_id
        OR NEW.public_id IS DISTINCT FROM OLD.public_id
        OR NEW.title IS DISTINCT FROM OLD.title
        OR NEW.content IS DISTINCT FROM OLD.content
        OR NEW.area_of_interest IS DISTINCT FROM OLD.area_of_interest
        OR NEW.latitude IS DISTINCT FROM OLD.latitude
        OR NEW.longitude IS DISTINCT FROM OLD.longitude
    ) THEN
        RAISE EXCEPTION 'incident base data is immutable after first phase validation' USING ERRCODE = '55000';
    END IF;
    IF OLD.status_code <> 'open' AND NEW.status_code IS DISTINCT FROM OLD.status_code THEN
        RAISE EXCEPTION 'closed or discarded incident cannot be reopened' USING ERRCODE = '55000';
    END IF;
    IF NEW.status_code IS DISTINCT FROM OLD.status_code THEN
        IF NEW.status_code = 'closed' AND NOT EXISTS (
            SELECT 1 FROM app.phase_validations v
            JOIN app.incident_phases p ON p.id=v.phase_id
            WHERE p.incident_id=OLD.id AND p.stage_code='mitigation'
        ) THEN
            RAISE EXCEPTION 'incident can close only after mitigation validation' USING ERRCODE = '55000';
        ELSIF NEW.status_code = 'discarded' AND NOT EXISTS (
            SELECT 1 FROM app.phase_validations v
            JOIN app.incident_phases p ON p.id=v.phase_id
            JOIN app.phase_reviews r ON r.phase_id=p.id
            WHERE p.incident_id=OLD.id AND p.stage_code='reconnaissance' AND r.finding_code='false-positive'
        ) THEN
            RAISE EXCEPTION 'incident can be discarded only by a validated false positive' USING ERRCODE = '55000';
        ELSIF NEW.status_code NOT IN ('open','closed','discarded') THEN
            RAISE EXCEPTION 'invalid workflow status transition' USING ERRCODE = '55000';
        END IF;
    END IF;
    RETURN NEW;
END $$;

