RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_actor_setting text := current_setting('app.actor_user_id', true);
    v_actor_user_id uuid;
BEGIN
    IF v_actor_setting ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
       AND EXISTS (SELECT 1 FROM public."AspNetUsers" WHERE "Id" = v_actor_setting::uuid) THEN
        v_actor_user_id := v_actor_setting::uuid;
    END IF;

    INSERT INTO app.audit_events
        (actor_user_id, action, outcome, entity_type, entity_id, changes, security_context)
    VALUES
        (v_actor_user_id,
         CASE TG_OP WHEN 'INSERT' THEN 'catalog.option.insert' ELSE 'catalog.option.update' END,
         'succeeded',
         'catalog_option',
         NEW.catalog_key || ':' || NEW.code,
         jsonb_build_object(
             'before', CASE WHEN TG_OP = 'UPDATE' THEN jsonb_build_object(
                 'label', OLD.label,
                 'sortOrder', OLD.sort_order,
                 'active', OLD.is_active,
                 'version', OLD.version,
                 'stageCodes', OLD.stage_codes,
                 'metadata', OLD.metadata) ELSE NULL END,
             'after', jsonb_build_object(
                 'label', NEW.label,
                 'sortOrder', NEW.sort_order,
                 'active', NEW.is_active,
                 'version', NEW.version,
                 'stageCodes', NEW.stage_codes,
                 'metadata', NEW.metadata)),
         jsonb_build_object('databaseRole', session_user));
    RETURN NEW;
END $$;

