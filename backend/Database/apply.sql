CREATE TABLE IF NOT EXISTS app.incidents (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    public_id text NOT NULL UNIQUE,
    owner_user_id uuid REFERENCES public."AspNetUsers"("Id") ON DELETE RESTRICT,
    legacy_user_id text,
    title varchar(120) NOT NULL,
    content varchar(10000) NOT NULL DEFAULT '',
    area_of_interest varchar(100),
    latitude double precision,
    longitude double precision,
    status_catalog_key text NOT NULL DEFAULT 'workflowStatuses' CHECK (status_catalog_key = 'workflowStatuses'),
    status_code text NOT NULL DEFAULT 'open',
    revision integer NOT NULL DEFAULT 0 CHECK (revision >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    deleted_by_user_id uuid REFERENCES public."AspNetUsers"("Id") ON DELETE RESTRICT,
    CONSTRAINT fk_incident_status FOREIGN KEY (status_catalog_key, status_code)
        REFERENCES app.catalog_options(catalog_key, code) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_incident_public_id CHECK (public_id = btrim(public_id) AND public_id <> ''),
    CONSTRAINT ck_incident_coordinates CHECK (
        (latitude IS NULL AND longitude IS NULL)
        OR (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)
    ),
    CONSTRAINT ck_incident_deletion CHECK (
        (deleted_at IS NULL AND deleted_by_user_id IS NULL)
        OR deleted_at IS NOT NULL
    )
);

