CREATE OR REPLACE FUNCTION app.verify_incident_phase_set()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_incident_id uuid;
    v_stages text[];
    v_review_count integer;
    v_detail_count integer;
BEGIN
    IF TG_TABLE_NAME = 'incidents' THEN
        v_incident_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END;
    ELSE
        v_incident_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.incident_id ELSE NEW.incident_id END;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM app.incidents WHERE id = v_incident_id) THEN
        IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
    END IF;

    SELECT array_agg(stage_code ORDER BY stage_code), count(*)
      INTO v_stages, v_review_count
      FROM app.incident_phases
     WHERE incident_id = v_incident_id;

    IF v_review_count <> 4 OR v_stages <> ARRAY['indications','mitigation','reconnaissance','surveillance']::text[] THEN
        RAISE EXCEPTION 'incident % must contain exactly the four workflow stages', v_incident_id
            USING ERRCODE = '23514';
    END IF;

    SELECT count(*) INTO v_review_count
      FROM app.phase_reviews r JOIN app.incident_phases p ON p.id = r.phase_id
     WHERE p.incident_id = v_incident_id;
    SELECT
        (SELECT count(*) FROM app.phase_indications d JOIN app.incident_phases p ON p.id=d.phase_id WHERE p.incident_id=v_incident_id)
      + (SELECT count(*) FROM app.phase_reconnaissance d JOIN app.incident_phases p ON p.id=d.phase_id WHERE p.incident_id=v_incident_id)
      + (SELECT count(*) FROM app.phase_surveillance d JOIN app.incident_phases p ON p.id=d.phase_id WHERE p.incident_id=v_incident_id)
      + (SELECT count(*) FROM app.phase_mitigation d JOIN app.incident_phases p ON p.id=d.phase_id WHERE p.incident_id=v_incident_id)
      INTO v_detail_count;
    IF v_review_count <> 4 OR v_detail_count <> 4 THEN
        RAISE EXCEPTION 'incident % must contain one review and one typed detail per stage', v_incident_id
            USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END $$;

